/* 
	DESAFIO:
    SELECIONE MATRICULA, NOME, DT_NASCIMENTO, CARGO DO EMPREGADO,
    SALARIO E O DEPARTAMENTO ONDE ELE TRABALHO
*/

SELECT MATRICULA, NOME, DT_NASCIMENTO AS BIRTHDAY, 
NM_CARGO AS CARGO, SALARIO, NM_DEPARTAMENTO AS DEPARTAMENTO
FROM TB_EMPREGADO INNER JOIN TB_CARGO
ON FK_CARGO = ID_CARGO INNER JOIN TB_DEPARTAMENTO
ON FK_DEPARTAMENTO = ID_DEPARTAMENTO ORDER BY NOME;

