/*
	1 - Selecione nome do empregado, cargo e salario, dos empregados que trabalham no 
	departamento Tecnologia da Informação
    
    2 - Selecione o nome dos empregados e departamentos dos empregados que são estagiarios
	e não trabalham da Tecnologia da Informação
    
    3 - Selecione a contagem de quantos empregados tem trabalhando em cada departamento,
	departamentos com nenhum empregado deverá apresentar a contagem 0
    
    4 - Selecione a contagem de quantos empregados tem por cargo
    
    5 - Selecione a soma dos salarios dos empregados por departamento
*/

-- 1
SELECT NOME, NM_CARGO AS CARGO, SALARIO, 
NM_DEPARTAMENTO AS DEPARTAMENTO FROM TB_EMPREGADO 
INNER JOIN TB_CARGO ON FK_CARGO = ID_CARGO 
INNER JOIN TB_DEPARTAMENTO ON FK_DEPARTAMENTO = ID_DEPARTAMENTO 
WHERE NM_DEPARTAMENTO = 'Tecnologia da Informação'
ORDER BY NOME;

-- 2
SELECT NOME, NM_DEPARTAMENTO AS DEPARTAMENTO, NM_CARGO AS CARGO FROM TB_EMPREGADO 
INNER JOIN TB_DEPARTAMENTO ON FK_DEPARTAMENTO = ID_DEPARTAMENTO 
INNER JOIN TB_CARGO ON FK_CARGO = ID_CARGO
WHERE NM_CARGO = 'Estagiário'
AND NM_DEPARTAMENTO <> 'Tecnologia da Informação';

-- 3
SELECT NM_DEPARTAMENTO AS DEPARTAMENTO, COUNT(MATRICULA) TOTAL_EMPREGADOS
FROM TB_DEPARTAMENTO LEFT JOIN TB_EMPREGADO
ON FK_DEPARTAMENTO = ID_DEPARTAMENTO
GROUP BY NM_DEPARTAMENTO ORDER BY TOTAL_EMPREGADOS DESC;

-- 4
SELECT NM_CARGO AS CARGO, COUNT(MATRICULA) TOTAL_EMPREGADOS
FROM TB_EMPREGADO RIGHT JOIN TB_CARGO
ON FK_CARGO = ID_CARGO
GROUP BY NM_CARGO ORDER BY TOTAL_EMPREGADOS DESC;

-- 5
SELECT NM_DEPARTAMENTO AS DEPARTAMENTO, SUM(SALARIO) AS SOMA_SALARIOS
FROM TB_DEPARTAMENTO LEFT JOIN TB_EMPREGADO 
ON FK_DEPARTAMENTO = ID_DEPARTAMENTO LEFT JOIN TB_CARGO
ON FK_CARGO = ID_CARGO
GROUP BY NM_DEPARTAMENTO;